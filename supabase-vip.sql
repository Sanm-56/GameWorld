create or replace function public.obtener_estado_vip(p_usuario text, p_codigo text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  codigo_limpio text := btrim(coalesce(p_codigo, ''));
  codigo_usuario text;
  membresia record;
  expirado boolean := false;
begin
  if usuario_limpio = '' then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Inicia sesion para entrar a la Zona VIP.');
  end if;

  if to_regclass('public.usuarios') is null then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'No se pudo validar tu usuario.');
  end if;

  execute 'select codigo::text from public.usuarios where usuario = $1 limit 1'
  into codigo_usuario
  using usuario_limpio;

  if codigo_usuario is null then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Inicia sesion para entrar a la Zona VIP.');
  end if;

  if codigo_limpio = '' then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Vuelve a iniciar sesion para validar tu acceso VIP.');
  end if;

  if codigo_usuario <> codigo_limpio then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'No se pudo validar tu sesion VIP.');
  end if;

  select *
  into membresia
  from public.vip_memberships
  where usuario_id = usuario_limpio
  limit 1;

  if not found then
    return jsonb_build_object(
      'ok', true,
      'is_active', false,
      'is_vip', false,
      'expires_at', null,
      'mensaje', 'No eres VIP todavia. Puedes comprar el acceso VIP desde la tienda.'
    );
  end if;

  expirado := membresia.expires_at is not null and membresia.expires_at <= now();

  return jsonb_build_object(
    'ok', true,
    'is_active', membresia.is_active and not expirado,
    'is_vip', membresia.is_active and not expirado,
    'expires_at', membresia.expires_at,
    'mensaje', case
      when membresia.is_active and not expirado then 'Acceso VIP activo.'
      when expirado then 'Tu acceso VIP expiro.'
      else 'Tu acceso VIP no esta activo.'
    end
  );
end;
$$;

create or replace function public.registrar_resultado_juego_vip(
  p_usuario text,
  p_codigo text default null,
  p_game_key text default null,
  p_game_title text default null,
  p_mode text default null,
  p_score integer default 0,
  p_metrics jsonb default '{}'::jsonb,
  p_rewards jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estado jsonb;
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  game_key_limpio text := lower(btrim(coalesce(p_game_key, '')));
  game_title_limpio text := btrim(coalesce(p_game_title, p_game_key, 'Juego VIP'));
  clean_score integer := greatest(0, coalesce(p_score, 0));
  clean_metrics jsonb := coalesce(p_metrics, '{}'::jsonb);
  resultado public.vip_game_results%rowtype;
  reward_coins bigint;
  reward_xp bigint;
  reward_tickets bigint;
  reward_payload jsonb;
  wallet public.vip_wallets%rowtype;
  metric_hits bigint := 0;
  metric_accuracy numeric := 0;
  metric_combo bigint := 0;
  bingo_room_id text;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  if game_key_limpio = '' then
    return jsonb_build_object('ok', false, 'mensaje', 'Juego VIP invalido.');
  end if;

  if game_key_limpio = 'reflejos-vip' then
    metric_hits := case
      when coalesce(clean_metrics->>'hits', '') ~ '^[0-9]+$' then (clean_metrics->>'hits')::bigint
      else 0
    end;
    metric_accuracy := case
      when coalesce(clean_metrics->>'accuracy', '') ~ '^[0-9]+(\.[0-9]+)?$' then least(100, greatest(0, (clean_metrics->>'accuracy')::numeric))
      else 0
    end;
    metric_combo := case
      when coalesce(clean_metrics->>'bestCombo', clean_metrics->>'combo', '') ~ '^[0-9]+$' then coalesce(clean_metrics->>'bestCombo', clean_metrics->>'combo')::bigint
      else 0
    end;
    reward_coins := least(180, floor(clean_score / 18.0)::bigint + floor(metric_hits / 4.0)::bigint);
    reward_xp := least(320, floor(clean_score / 10.0)::bigint + round(metric_accuracy / 4.0)::bigint);
    reward_tickets := case when clean_score >= 500 or metric_combo >= 20 then 1 else 0 end;
  elsif game_key_limpio = 'bingo-vip' and lower(coalesce(clean_metrics->>'bingo', 'false')) = 'true' then
    bingo_room_id := nullif(btrim(coalesce(clean_metrics->>'roomId', '')), '');

    if bingo_room_id is not null then
      select *
      into resultado
      from public.vip_game_results
      where usuario_id = usuario_limpio
        and game_key = 'bingo-vip'
        and metrics->>'roomId' = bingo_room_id
        and lower(coalesce(metrics->>'bingo', 'false')) = 'true'
      order by created_at asc
      limit 1;

      if found then
        insert into public.vip_wallets (usuario_id)
        values (usuario_limpio)
        on conflict (usuario_id) do nothing;

        select *
        into wallet
        from public.vip_wallets
        where usuario_id = usuario_limpio;

        return jsonb_build_object(
          'ok', true,
          'duplicate', true,
          'mensaje', 'Este Bingo VIP ya tenia recompensa registrada.',
          'wallet', jsonb_build_object(
            'usuario_id', wallet.usuario_id,
            'vipCoins', wallet.vip_coins,
            'vipXp', wallet.vip_xp,
            'vipTickets', wallet.vip_tickets,
            'updated_at', wallet.updated_at
          ),
          'result', jsonb_build_object(
            'id', resultado.id,
            'usuario_id', resultado.usuario_id,
            'game_key', resultado.game_key,
            'game_title', resultado.game_title,
            'mode', resultado.mode,
            'score', resultado.score,
            'metrics', resultado.metrics,
            'rewards', resultado.rewards,
            'origin', resultado.origin,
            'created_at', resultado.created_at
          )
        );
      end if;
    end if;

    reward_coins := 35;
    reward_xp := 80;
    reward_tickets := 1;
  else
    reward_coins := 0;
    reward_xp := 0;
    reward_tickets := 0;
  end if;

  reward_payload := jsonb_build_object(
    'vipCoins', reward_coins,
    'vipXp', reward_xp,
    'vipTickets', reward_tickets
  );

  insert into public.vip_game_results (
    usuario_id,
    game_key,
    game_title,
    mode,
    score,
    metrics,
    rewards,
    origin
  )
  values (
    usuario_limpio,
    game_key_limpio,
    game_title_limpio,
    nullif(btrim(coalesce(p_mode, '')), ''),
    clean_score,
    clean_metrics,
    reward_payload,
    'vip'
  )
  returning *
  into resultado;

  insert into public.vip_wallets (usuario_id, vip_coins, vip_xp, vip_tickets)
  values (usuario_limpio, reward_coins, reward_xp, reward_tickets)
  on conflict (usuario_id) do update
    set vip_coins = public.vip_wallets.vip_coins + excluded.vip_coins,
        vip_xp = public.vip_wallets.vip_xp + excluded.vip_xp,
        vip_tickets = public.vip_wallets.vip_tickets + excluded.vip_tickets,
        updated_at = now()
  returning *
  into wallet;

  if reward_coins > 0 or reward_xp > 0 or reward_tickets > 0 then
    insert into public.vip_wallet_transactions (
      usuario_id,
      tipo,
      vip_coins_delta,
      vip_xp_delta,
      vip_tickets_delta,
      source,
      reference_id,
      detail
    )
    values (
      usuario_limpio,
      'earn',
      reward_coins,
      reward_xp,
      reward_tickets,
      'vip_game',
      resultado.id::text,
      jsonb_build_object('game_key', resultado.game_key, 'mode', resultado.mode, 'score', resultado.score)
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    ),
    'result', jsonb_build_object(
      'id', resultado.id,
      'usuario_id', resultado.usuario_id,
      'game_key', resultado.game_key,
      'game_title', resultado.game_title,
      'mode', resultado.mode,
      'score', resultado.score,
      'metrics', resultado.metrics,
      'rewards', resultado.rewards,
      'origin', resultado.origin,
      'created_at', resultado.created_at
    )
  );
end;
$$;

create or replace function public.obtener_billetera_vip(
  p_usuario text,
  p_codigo text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estado jsonb;
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  wallet public.vip_wallets%rowtype;
  convertido_hoy bigint;
  limite_diario bigint := 50;
  tasa integer := 100;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  insert into public.vip_wallets (usuario_id)
  values (usuario_limpio)
  on conflict (usuario_id) do nothing;

  select *
  into wallet
  from public.vip_wallets
  where usuario_id = usuario_limpio;

  select coalesce(sum(vip_coins_spent), 0)
  into convertido_hoy
  from public.vip_coin_conversions
  where usuario_id = usuario_limpio
    and created_at >= date_trunc('day', now());

  return jsonb_build_object(
    'ok', true,
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    ),
    'conversion', jsonb_build_object(
      'rate', tasa,
      'dailyLimitVipCoins', limite_diario,
      'convertedTodayVipCoins', convertido_hoy,
      'remainingTodayVipCoins', greatest(0, limite_diario - convertido_hoy)
    )
  );
end;
$$;

create or replace function public.convertir_monedas_vip(
