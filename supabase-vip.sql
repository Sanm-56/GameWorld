  p_description text default '',
  p_event_type text default 'general',
  p_starts_at timestamptz default null,
  p_ends_at timestamptz default null,
  p_is_active boolean default true,
  p_related_game text default null,
  p_rewards jsonb default '{}'::jsonb,
  p_config jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  nombre_limpio text := btrim(coalesce(p_name, ''));
  tipo_limpio text := lower(regexp_replace(btrim(coalesce(p_event_type, 'general')), '[^a-zA-Z0-9_-]', '', 'g'));
  juego_limpio text := nullif(lower(regexp_replace(btrim(coalesce(p_related_game, '')), '[^a-zA-Z0-9_-]', '', 'g')), '');
