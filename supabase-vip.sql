create or replace function public.vip_bingo_tiene_linea(p_card jsonb, p_marked jsonb)
returns boolean
language plpgsql
stable
as $$
declare
  fila integer;
  columna integer;
begin
  if jsonb_array_length(coalesce(p_card, '[]'::jsonb)) <> 25 then
    return false;
  end if;

  for fila in 0..4 loop
    if public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 1)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 2)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 3)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 4) then
      return true;
    end if;
  end loop;

  for columna in 0..4 loop
    if public.vip_bingo_numero_marcado(p_card, p_marked, columna)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 5)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 10)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 15)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 20) then
      return true;
    end if;
  end loop;

  if public.vip_bingo_numero_marcado(p_card, p_marked, 0)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 6)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 12)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 18)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 24) then
    return true;
  end if;

  if public.vip_bingo_numero_marcado(p_card, p_marked, 4)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 8)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 12)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 16)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 20) then
    return true;
  end if;

  return false;
end;
$$;

create or replace function public.vip_bingo_payload(p_room_id text, p_usuario text)
returns jsonb
language plpgsql
stable
as $$
declare
  sala record;
  jugador record;
  jugador_encontrado boolean := false;
  jugadores jsonb;
begin
  select *
  into sala
  from public.vip_bingo_rooms
  where id = p_room_id;

  if not found then
    return jsonb_build_object('ok', false, 'mensaje', 'Sala VIP no encontrada.');
  end if;

  select *
  into jugador
  from public.vip_bingo_players
  where room_id = p_room_id
    and usuario_id = p_usuario;
  jugador_encontrado := found;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'usuario_id', usuario_id,
      'joined_at', joined_at
    )
    order by joined_at
  ), '[]'::jsonb)
  into jugadores
  from public.vip_bingo_players
  where room_id = p_room_id;

  return jsonb_build_object(
    'ok', true,
    'room', jsonb_build_object(
      'id', sala.id,
      'created_by', sala.created_by,
      'status', sala.status,
      'called_numbers', sala.called_numbers,
      'winner_usuario_id', sala.winner_usuario_id,
      'created_at', sala.created_at,
      'updated_at', sala.updated_at
    ),
    'player', case when not jugador_encontrado then null else jsonb_build_object(
      'usuario_id', jugador.usuario_id,
      'card', jugador.card,
      'marked_numbers', jugador.marked_numbers,
      'joined_at', jugador.joined_at,
      'updated_at', jugador.updated_at
    ) end,
    'players', jugadores
  );
end;
$$;

