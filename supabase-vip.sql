    return jsonb_build_object('ok', false, 'mensaje', 'El evento VIP necesita nombre.');
  end if;

  if p_starts_at is null or p_ends_at is null or p_ends_at <= p_starts_at then
    return jsonb_build_object('ok', false, 'mensaje', 'Fechas invalidas para evento VIP.');
  end if;

  if p_event_id is null then
    insert into public.vip_events (
      name,
      description,
      event_type,
      starts_at,
      ends_at,
      is_active,
      related_game,
      rewards,
      config
