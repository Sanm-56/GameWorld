create or replace function public.admin_vip_private_finalizar_torneo(
  p_clave text,
  p_tournament_id bigint,
  p_winner_usuario text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  ganador_limpio text := nullif(btrim(coalesce(p_winner_usuario, '')), '');
  torneo public.vip_private_tournaments%rowtype;
begin
  if not public.validar_admin_torneo(p_clave) then
    return jsonb_build_object('ok', false, 'mensaje', 'Clave admin invalida');
  end if;

  select *
  into torneo
  from public.vip_private_tournaments
  where id = p_tournament_id
  for update;

  if not found then
    return jsonb_build_object('ok', false, 'mensaje', 'Minitorneo VIP privado no encontrado.');
  end if;

  if ganador_limpio is not null and not exists (
    select 1
    from public.vip_private_tournament_players
    where tournament_id = torneo.id
      and usuario_id = ganador_limpio
      and entry_status in ('confirmada', 'cortesia')
  ) then
    return jsonb_build_object('ok', false, 'mensaje', 'El ganador no esta confirmado en esta sala.');
  end if;

  update public.vip_private_tournament_results
  set is_winner = false,
      updated_at = now()
  where tournament_id = torneo.id;

  if ganador_limpio is not null then
    update public.vip_private_tournament_results
    set is_winner = true,
        position = coalesce(position, 1),
        updated_at = now()
    where tournament_id = torneo.id
      and usuario_id = ganador_limpio
      and valid = true;
  end if;

  update public.vip_private_tournaments
  set status = 'finalizada',
      winner_usuario_id = ganador_limpio,
      ends_at = coalesce(ends_at, now()),
      updated_at = now()
  where id = torneo.id
  returning *
  into torneo;

  return jsonb_build_object(
    'ok', true,
    'mensaje', 'Minitorneo VIP privado finalizado.',
    'tournament', jsonb_build_object(
      'id', torneo.id,
      'status', torneo.status,
