create or replace function public.vip_private_tournament_payload(
  p_tournament_id bigint,
  p_usuario text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  torneo public.vip_private_tournaments%rowtype;
  participante public.vip_private_tournament_players%rowtype;
  participantes jsonb;
  resultados jsonb;
begin
  select *
  into torneo
  from public.vip_private_tournaments
