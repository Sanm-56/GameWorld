    values (
      nombre_limpio,
      btrim(coalesce(p_description, '')),
      tipo_limpio,
      p_starts_at,
      p_ends_at,
      coalesce(p_is_active, true),
      juego_limpio,
      coalesce(p_rewards, '{}'::jsonb),
      coalesce(p_config, '{}'::jsonb)
    )
    returning *
    into evento;
  else
    update public.vip_events
    set name = nombre_limpio,
        description = btrim(coalesce(p_description, '')),
        event_type = tipo_limpio,
        starts_at = p_starts_at,
        ends_at = p_ends_at,
        is_active = coalesce(p_is_active, true),
        related_game = juego_limpio,
        rewards = coalesce(p_rewards, '{}'::jsonb),
        config = coalesce(p_config, '{}'::jsonb),
        updated_at = now()
    where id = p_event_id
    returning *
    into evento;

    if not found then
      return jsonb_build_object('ok', false, 'mensaje', 'Evento VIP no encontrado.');
    end if;
  end if;

  return jsonb_build_object(
    'ok', true,
    'mensaje', 'Evento VIP guardado.',
    'event', jsonb_build_object(
      'id', evento.id,
      'name', evento.name,
      'description', evento.description,
      'event_type', evento.event_type,
      'starts_at', evento.starts_at,
      'ends_at', evento.ends_at,
      'is_active', evento.is_active,
      'related_game', evento.related_game,
      'rewards', evento.rewards,
      'config', evento.config,
      'created_at', evento.created_at,
      'updated_at', evento.updated_at
    )
  );
end;
