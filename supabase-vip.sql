create or replace function public.vip_roulette_girar(
  p_usuario text,
  p_codigo text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estado jsonb;
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  ultimo record;
  premio record;
  total_peso integer;
  punto integer;
  acumulado integer := 0;
  cooldown_horas integer := 24;
  cooldown_fin timestamptz := now() + make_interval(hours => 24);
  reward_coins bigint := 0;
  reward_xp bigint := 0;
  reward_tickets bigint := 0;
  spin_id bigint;
  snapshot jsonb;
  wallet public.vip_wallets%rowtype;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  select *
  into ultimo
  from public.vip_roulette_spins
  where usuario_id = usuario_limpio
  order by created_at desc
  limit 1;

  if found and ultimo.cooldown_until > now() then
    return jsonb_build_object(
      'ok', false,
      'mensaje', 'Ya usaste tu tirada VIP de hoy.',
      'cooldownUntil', ultimo.cooldown_until
    );
  end if;

  select coalesce(sum(weight), 0)
  into total_peso
  from public.vip_roulette_rewards
  where is_active = true;

  if total_peso <= 0 then
    return jsonb_build_object('ok', false, 'mensaje', 'No hay premios VIP activos.');
  end if;

  punto := floor(random() * total_peso + 1)::integer;

  for premio in
    select *
    from public.vip_roulette_rewards
    where is_active = true
    order by id
  loop
    acumulado := acumulado + premio.weight;
    if acumulado >= punto then
      exit;
    end if;
  end loop;

  if premio.id is null then
    return jsonb_build_object('ok', false, 'mensaje', 'No se pudo seleccionar premio VIP.');
  end if;

  if premio.reward_type = 'vip_coins' then
    reward_coins := premio.amount;
  elsif premio.reward_type = 'vip_xp' then
    reward_xp := premio.amount;
  elsif premio.reward_type = 'vip_tickets' then
    reward_tickets := premio.amount;
  end if;

  snapshot := jsonb_build_object(
    'key', premio.reward_key,
    'label', premio.label,
    'type', premio.reward_type,
    'amount', premio.amount
  );

  insert into public.vip_roulette_spins (usuario_id, reward_id, reward_snapshot, cooldown_until)
  values (usuario_limpio, premio.id, snapshot, cooldown_fin)
  returning id
  into spin_id;

  insert into public.vip_wallets (usuario_id, vip_coins, vip_xp, vip_tickets)
  values (usuario_limpio, reward_coins, reward_xp, reward_tickets)
  on conflict (usuario_id) do update
    set vip_coins = public.vip_wallets.vip_coins + excluded.vip_coins,
        vip_xp = public.vip_wallets.vip_xp + excluded.vip_xp,
        vip_tickets = public.vip_wallets.vip_tickets + excluded.vip_tickets,
        updated_at = now()
  returning *
  into wallet;

  if reward_coins > 0 or reward_xp > 0 or reward_tickets > 0 then
    insert into public.vip_wallet_transactions (
      usuario_id,
      tipo,
      vip_coins_delta,
      vip_xp_delta,
      vip_tickets_delta,
      source,
      reference_id,
      detail
    )
    values (
      usuario_limpio,
      'earn',
      reward_coins,
      reward_xp,
      reward_tickets,
      'vip_roulette',
      spin_id::text,
      snapshot
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'mensaje', 'Tirada VIP completada.',
    'spinId', spin_id,
    'reward', snapshot,
    'cooldownUntil', cooldown_fin,
    'cooldownHours', cooldown_horas,
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    )
  );
end;
$$;

