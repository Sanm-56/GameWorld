-- Sistema VIP base para GameWorld.
-- Ejecutar en Supabase SQL Editor despues de las migraciones principales.

create table if not exists public.vip_memberships (
  id bigint generated by default as identity primary key,
  usuario_id text not null unique,
  is_active boolean not null default true,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vip_memberships_usuario_id_check check (btrim(usuario_id) <> '')
);

create index if not exists vip_memberships_active_idx
on public.vip_memberships (is_active, expires_at);

create or replace function public.vip_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists vip_memberships_touch_updated_at on public.vip_memberships;

create trigger vip_memberships_touch_updated_at
before update on public.vip_memberships
for each row
execute function public.vip_touch_updated_at();

create or replace function public.obtener_estado_vip(p_usuario text, p_codigo text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  codigo_limpio text := btrim(coalesce(p_codigo, ''));
  codigo_usuario text;
  membresia record;
  expirado boolean := false;
begin
  if usuario_limpio = '' then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Inicia sesion para entrar a la Zona VIP.');
  end if;

  if to_regclass('public.usuarios') is null then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'No se pudo validar tu usuario.');
  end if;

  execute 'select codigo::text from public.usuarios where usuario = $1 limit 1'
  into codigo_usuario
  using usuario_limpio;

  if codigo_usuario is null then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Inicia sesion para entrar a la Zona VIP.');
  end if;

  if codigo_limpio = '' then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Vuelve a iniciar sesion para validar tu acceso VIP.');
  end if;

  if codigo_usuario <> codigo_limpio then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'No se pudo validar tu sesion VIP.');
  end if;

  select *
  into membresia
  from public.vip_memberships
  where usuario_id = usuario_limpio
  limit 1;

  if not found then
    return jsonb_build_object(
      'ok', true,
      'is_active', false,
      'is_vip', false,
      'expires_at', null,
      'mensaje', 'No eres VIP todavia. Puedes comprar el acceso VIP desde la tienda.'
    );
  end if;

  expirado := membresia.expires_at is not null and membresia.expires_at <= now();

  return jsonb_build_object(
    'ok', true,
    'is_active', membresia.is_active and not expirado,
    'is_vip', membresia.is_active and not expirado,
    'expires_at', membresia.expires_at,
    'mensaje', case
      when membresia.is_active and not expirado then 'Acceso VIP activo.'
      when expirado then 'Tu acceso VIP expiro.'
      else 'Tu acceso VIP no esta activo.'
    end
  );
end;
$$;

create or replace function public.admin_guardar_membresia_vip(
  p_clave text,
  p_usuario text,
  p_activo boolean default true,
  p_expires_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
begin
  if not public.validar_admin_torneo(p_clave) then
    return jsonb_build_object('ok', false, 'mensaje', 'Clave admin invalida');
  end if;

  if usuario_limpio = '' or to_regclass('public.usuarios') is null then
    return jsonb_build_object('ok', false, 'mensaje', 'Usuario invalido');
  end if;

  if not exists (select 1 from public.usuarios where usuario = usuario_limpio) then
    return jsonb_build_object('ok', false, 'mensaje', 'El usuario no existe');
  end if;

  insert into public.vip_memberships (usuario_id, is_active, expires_at)
  values (usuario_limpio, coalesce(p_activo, true), p_expires_at)
  on conflict (usuario_id) do update
  set is_active = excluded.is_active,
      expires_at = excluded.expires_at,
      updated_at = now();

  return jsonb_build_object('ok', true, 'mensaje', 'Membresia VIP guardada');
end;
$$;

create or replace function public.admin_listar_membresias_vip(p_clave text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.validar_admin_torneo(p_clave) then
    return jsonb_build_object('ok', false, 'mensaje', 'Clave admin invalida', 'items', '[]'::jsonb);
  end if;

  return jsonb_build_object(
    'ok', true,
    'items',
    coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'usuario_id', usuario_id,
          'is_active', is_active,
          'expires_at', expires_at,
          'created_at', created_at,
          'updated_at', updated_at,
          'is_valid', is_active and (expires_at is null or expires_at > now())
        )
        order by updated_at desc
      )
      from public.vip_memberships
    ), '[]'::jsonb)
  );
end;
$$;

alter table public.vip_memberships enable row level security;

drop policy if exists vip_memberships_no_direct_select on public.vip_memberships;
drop policy if exists vip_memberships_no_direct_insert on public.vip_memberships;
drop policy if exists vip_memberships_no_direct_update on public.vip_memberships;
drop policy if exists vip_memberships_no_direct_delete on public.vip_memberships;

revoke all on table public.vip_memberships from anon, authenticated;
grant execute on function public.obtener_estado_vip(text, text) to anon, authenticated;
grant execute on function public.admin_guardar_membresia_vip(text, text, boolean, timestamptz) to anon, authenticated;
grant execute on function public.admin_listar_membresias_vip(text) to anon, authenticated;
