  cantidad bigint := greatest(0, coalesce(p_vip_coins, 0));
  tasa integer := 100;
  limite_diario bigint := 50;
  convertido_hoy bigint;
  disponible_hoy bigint;
  monedas_normales bigint;
  wallet public.vip_wallets%rowtype;
  saldo_normal bigint;
  conversion_id bigint;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  if cantidad <= 0 then
    return jsonb_build_object('ok', false, 'mensaje', 'Ingresa una cantidad valida de monedas VIP.');
  end if;

  if cantidad > limite_diario then
    return jsonb_build_object('ok', false, 'mensaje', 'La conversion supera el limite diario VIP.');
  end if;

  insert into public.vip_wallets (usuario_id)
  values (usuario_limpio)
  on conflict (usuario_id) do nothing;

  select *
  into wallet
  from public.vip_wallets
  where usuario_id = usuario_limpio
  for update;

  if wallet.vip_coins < cantidad then
    return jsonb_build_object('ok', false, 'mensaje', 'No tienes suficientes monedas VIP.');
  end if;

  select coalesce(sum(vip_coins_spent), 0)
  into convertido_hoy
  from public.vip_coin_conversions
  where usuario_id = usuario_limpio
    and created_at >= date_trunc('day', now());

  disponible_hoy := greatest(0, limite_diario - convertido_hoy);

  if cantidad > disponible_hoy then
    return jsonb_build_object(
      'ok', false,
      'mensaje', 'Ya alcanzaste el limite diario de conversion VIP.',
      'remainingTodayVipCoins', disponible_hoy
    );
  end if;

  monedas_normales := cantidad * tasa;

  update public.vip_wallets
  set vip_coins = vip_coins - cantidad,
      updated_at = now()
  where usuario_id = usuario_limpio
  returning *
  into wallet;

  insert into public.usuario_monedas (usuario_id, saldo)
  values (usuario_limpio, monedas_normales)
  on conflict (usuario_id) do update
    set saldo = public.usuario_monedas.saldo + excluded.saldo,
        updated_at = now()
  returning saldo
  into saldo_normal;

  insert into public.vip_coin_conversions (
    usuario_id,
    vip_coins_spent,
    normal_coins_received,
    conversion_rate
  )
  values (
    usuario_limpio,
    cantidad,
    monedas_normales,
    tasa
  )
  returning id
  into conversion_id;

  insert into public.vip_wallet_transactions (
    usuario_id,
    tipo,
    vip_coins_delta,
    normal_coins_delta,
    source,
    reference_id,
    detail
  )
  values (
    usuario_limpio,
    'convert',
    -cantidad,
    monedas_normales,
    'vip_conversion',
    conversion_id::text,
    jsonb_build_object('rate', tasa, 'dailyLimitVipCoins', limite_diario)
  );

  return jsonb_build_object(
    'ok', true,
    'mensaje', 'Conversion VIP completada.',
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    ),
    'conversion', jsonb_build_object(
      'id', conversion_id,
      'vipCoinsSpent', cantidad,
      'normalCoinsReceived', monedas_normales,
      'rate', tasa,
      'dailyLimitVipCoins', limite_diario,
      'convertedTodayVipCoins', convertido_hoy + cantidad,
      'remainingTodayVipCoins', greatest(0, limite_diario - convertido_hoy - cantidad)
    ),
    'normalCoinsBalance', saldo_normal
  );
end;
$$;

create or replace function public.vip_bingo_generar_carton()
returns jsonb
language plpgsql
as $$
declare
  b integer[];
  i integer[];
  n integer[];
  g integer[];
  o integer[];
  card integer[] := '{}';
  fila integer;
begin
  select array_agg(valor) into b from (select valor from generate_series(1, 15) valor order by random() limit 5) s;
  select array_agg(valor) into i from (select valor from generate_series(16, 30) valor order by random() limit 5) s;
  select array_agg(valor) into n from (select valor from generate_series(31, 45) valor order by random() limit 5) s;
  select array_agg(valor) into g from (select valor from generate_series(46, 60) valor order by random() limit 5) s;
  select array_agg(valor) into o from (select valor from generate_series(61, 75) valor order by random() limit 5) s;

  for fila in 1..5 loop
    card := card || b[fila] || i[fila] || case when fila = 3 then 0 else n[fila] end || g[fila] || o[fila];
  end loop;

  return to_jsonb(card);
end;
$$;

create or replace function public.vip_bingo_numero_marcado(p_card jsonb, p_marked jsonb, p_index integer)
