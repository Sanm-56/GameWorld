-- Sistema VIP base para GameWorld.
-- Ejecutar en Supabase SQL Editor despues de las migraciones principales.

create table if not exists public.vip_memberships (
  id bigint generated by default as identity primary key,
  usuario_id text not null unique,
  is_active boolean not null default true,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vip_memberships_usuario_id_check check (btrim(usuario_id) <> '')
);

create index if not exists vip_memberships_active_idx
on public.vip_memberships (is_active, expires_at);

create table if not exists public.vip_game_results (
  id bigint generated by default as identity primary key,
  usuario_id text not null,
  game_key text not null,
  game_title text not null,
  mode text,
  score integer not null default 0,
  metrics jsonb not null default '{}'::jsonb,
  rewards jsonb not null default '{}'::jsonb,
  origin text not null default 'vip',
  created_at timestamptz not null default now(),
  constraint vip_game_results_usuario_check check (btrim(usuario_id) <> ''),
  constraint vip_game_results_game_key_check check (btrim(game_key) <> ''),
  constraint vip_game_results_score_check check (score >= 0),
  constraint vip_game_results_origin_check check (origin = 'vip')
);

create index if not exists vip_game_results_usuario_idx
on public.vip_game_results (usuario_id, created_at desc);

create index if not exists vip_game_results_game_idx
on public.vip_game_results (game_key, score desc, created_at desc);

create table if not exists public.vip_wallets (
  usuario_id text primary key,
  vip_coins bigint not null default 0 check (vip_coins >= 0),
  vip_xp bigint not null default 0 check (vip_xp >= 0),
  vip_tickets bigint not null default 0 check (vip_tickets >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vip_wallets_usuario_check check (btrim(usuario_id) <> '')
);

create table if not exists public.vip_wallet_transactions (
  id bigint generated by default as identity primary key,
  usuario_id text not null,
  tipo text not null check (tipo in ('earn', 'spend', 'convert')),
  vip_coins_delta bigint not null default 0,
  vip_xp_delta bigint not null default 0,
  vip_tickets_delta bigint not null default 0,
  normal_coins_delta bigint not null default 0,
  source text not null default 'vip',
  reference_id text,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint vip_wallet_transactions_usuario_check check (btrim(usuario_id) <> '')
);

create index if not exists vip_wallet_transactions_usuario_idx
on public.vip_wallet_transactions (usuario_id, created_at desc);

create table if not exists public.vip_coin_conversions (
  id bigint generated by default as identity primary key,
  usuario_id text not null,
  vip_coins_spent bigint not null check (vip_coins_spent > 0),
  normal_coins_received bigint not null check (normal_coins_received > 0),
  conversion_rate integer not null default 100 check (conversion_rate > 0),
  created_at timestamptz not null default now(),
  constraint vip_coin_conversions_usuario_check check (btrim(usuario_id) <> '')
);

create index if not exists vip_coin_conversions_usuario_fecha_idx
on public.vip_coin_conversions (usuario_id, created_at desc);

create table if not exists public.vip_bingo_rooms (
  id text primary key,
  created_by text not null,
  status text not null default 'active' check (status in ('waiting', 'active', 'finished')),
  called_numbers jsonb not null default '[]'::jsonb,
  winner_usuario_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vip_bingo_rooms_id_check check (btrim(id) <> ''),
  constraint vip_bingo_rooms_created_by_check check (btrim(created_by) <> '')
);

create table if not exists public.vip_bingo_players (
  id bigint generated by default as identity primary key,
  room_id text not null references public.vip_bingo_rooms(id) on delete cascade,
  usuario_id text not null,
  card jsonb not null,
  marked_numbers jsonb not null default '[0]'::jsonb,
  joined_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (room_id, usuario_id),
  constraint vip_bingo_players_usuario_check check (btrim(usuario_id) <> ''),
  constraint vip_bingo_players_card_check check (jsonb_typeof(card) = 'array'),
  constraint vip_bingo_players_marked_check check (jsonb_typeof(marked_numbers) = 'array')
);

create index if not exists vip_bingo_players_room_idx
on public.vip_bingo_players (room_id, joined_at);

