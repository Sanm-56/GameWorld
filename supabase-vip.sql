  end if;

  if estado_limpio in ('confirmada', 'cortesia') then
    select count(*)::integer
    into cupos_confirmados
    from public.vip_private_tournament_players
    where tournament_id = torneo.id
      and entry_status in ('confirmada', 'cortesia')
      and usuario_id <> usuario_limpio;

    if cupos_confirmados >= torneo.max_players then
      return jsonb_build_object('ok', false, 'mensaje', 'El minitorneo VIP privado ya alcanzo el cupo maximo.');
    end if;
  end if;

  insert into public.vip_private_tournament_players (
    tournament_id,
    usuario_id,
    display_name,
    entry_status,
    confirmed_by,
    confirmed_at,
    notes
  )
  values (
    torneo.id,
    usuario_limpio,
    coalesce(nombre_limpio, usuario_limpio),
    estado_limpio,
    case when estado_limpio in ('confirmada', 'cortesia') then 'admin' else null end,
    case when estado_limpio in ('confirmada', 'cortesia') then now() else null end,
    btrim(coalesce(p_notes, ''))
  )
  on conflict (tournament_id, usuario_id) do update
    set display_name = coalesce(excluded.display_name, vip_private_tournament_players.display_name),
        entry_status = excluded.entry_status,
        confirmed_by = case when excluded.entry_status in ('confirmada', 'cortesia') then 'admin' else null end,
        confirmed_at = case when excluded.entry_status in ('confirmada', 'cortesia') then coalesce(vip_private_tournament_players.confirmed_at, now()) else null end,
        notes = excluded.notes,
        updated_at = now()
  returning *
  into participante;

  return jsonb_build_object(
    'ok', true,
    'mensaje', 'Inscripcion VIP privada actualizada.',
    'player', jsonb_build_object(
      'id', participante.id,
      'tournament_id', participante.tournament_id,
      'usuario_id', participante.usuario_id,
      'display_name', participante.display_name,
      'entry_status', participante.entry_status,
      'confirmed_at', participante.confirmed_at,
      'joined_at', participante.joined_at,
      'updated_at', participante.updated_at
    )
  );
end;
$$;

