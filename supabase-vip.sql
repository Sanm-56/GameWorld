create or replace function public.obtener_estado_vip(p_usuario text, p_codigo text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  codigo_limpio text := btrim(coalesce(p_codigo, ''));
  codigo_usuario text;
  membresia record;
  expirado boolean := false;
begin
  if usuario_limpio = '' then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Inicia sesion para entrar a la Zona VIP.');
  end if;

  if to_regclass('public.usuarios') is null then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'No se pudo validar tu usuario.');
  end if;

  execute 'select codigo::text from public.usuarios where usuario = $1 limit 1'
  into codigo_usuario
  using usuario_limpio;

  if codigo_usuario is null then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Inicia sesion para entrar a la Zona VIP.');
  end if;

  if codigo_limpio = '' then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'Vuelve a iniciar sesion para validar tu acceso VIP.');
  end if;

  if codigo_usuario <> codigo_limpio then
    return jsonb_build_object('ok', false, 'is_active', false, 'mensaje', 'No se pudo validar tu sesion VIP.');
  end if;

  select *
  into membresia
  from public.vip_memberships
  where usuario_id = usuario_limpio
  limit 1;

  if not found then
    return jsonb_build_object(
      'ok', true,
      'is_active', false,
      'is_vip', false,
      'expires_at', null,
      'mensaje', 'No eres VIP todavia. Puedes comprar el acceso VIP desde la tienda.'
    );
  end if;

  expirado := membresia.expires_at is not null and membresia.expires_at <= now();

  return jsonb_build_object(
    'ok', true,
    'is_active', membresia.is_active and not expirado,
    'is_vip', membresia.is_active and not expirado,
    'expires_at', membresia.expires_at,
    'mensaje', case
      when membresia.is_active and not expirado then 'Acceso VIP activo.'
      when expirado then 'Tu acceso VIP expiro.'
      else 'Tu acceso VIP no esta activo.'
    end
  );
end;
$$;

create or replace function public.registrar_resultado_juego_vip(
  p_usuario text,
  p_codigo text default null,
  p_game_key text default null,
  p_game_title text default null,
  p_mode text default null,
  p_score integer default 0,
  p_metrics jsonb default '{}'::jsonb,
  p_rewards jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estado jsonb;
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  game_key_limpio text := lower(btrim(coalesce(p_game_key, '')));
  game_title_limpio text := btrim(coalesce(p_game_title, p_game_key, 'Juego VIP'));
  resultado public.vip_game_results%rowtype;
  reward_coins bigint;
  reward_xp bigint;
  reward_tickets bigint;
  wallet public.vip_wallets%rowtype;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  if game_key_limpio = '' then
    return jsonb_build_object('ok', false, 'mensaje', 'Juego VIP invalido.');
  end if;

  insert into public.vip_game_results (
    usuario_id,
    game_key,
    game_title,
    mode,
    score,
    metrics,
    rewards,
    origin
  )
  values (
    usuario_limpio,
    game_key_limpio,
    game_title_limpio,
    nullif(btrim(coalesce(p_mode, '')), ''),
    greatest(0, coalesce(p_score, 0)),
    coalesce(p_metrics, '{}'::jsonb),
    coalesce(p_rewards, '{}'::jsonb),
    'vip'
  )
  returning *
  into resultado;

  reward_coins := greatest(0, coalesce((p_rewards->>'vipCoins')::bigint, (p_rewards->>'vip_coins')::bigint, 0));
  reward_xp := greatest(0, coalesce((p_rewards->>'vipXp')::bigint, (p_rewards->>'vip_xp')::bigint, 0));
  reward_tickets := greatest(0, coalesce((p_rewards->>'vipTickets')::bigint, (p_rewards->>'vip_tickets')::bigint, 0));

  insert into public.vip_wallets (usuario_id, vip_coins, vip_xp, vip_tickets)
  values (usuario_limpio, reward_coins, reward_xp, reward_tickets)
  on conflict (usuario_id) do update
    set vip_coins = public.vip_wallets.vip_coins + excluded.vip_coins,
        vip_xp = public.vip_wallets.vip_xp + excluded.vip_xp,
        vip_tickets = public.vip_wallets.vip_tickets + excluded.vip_tickets,
        updated_at = now()
  returning *
  into wallet;

  if reward_coins > 0 or reward_xp > 0 or reward_tickets > 0 then
    insert into public.vip_wallet_transactions (
      usuario_id,
      tipo,
      vip_coins_delta,
      vip_xp_delta,
      vip_tickets_delta,
      source,
      reference_id,
      detail
    )
    values (
      usuario_limpio,
      'earn',
      reward_coins,
      reward_xp,
      reward_tickets,
      'vip_game',
      resultado.id::text,
      jsonb_build_object('game_key', resultado.game_key, 'mode', resultado.mode, 'score', resultado.score)
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    ),
    'result', jsonb_build_object(
      'id', resultado.id,
      'usuario_id', resultado.usuario_id,
      'game_key', resultado.game_key,
      'game_title', resultado.game_title,
      'mode', resultado.mode,
      'score', resultado.score,
      'metrics', resultado.metrics,
      'rewards', resultado.rewards,
      'origin', resultado.origin,
      'created_at', resultado.created_at
    )
  );
end;
$$;

create or replace function public.obtener_billetera_vip(
  p_usuario text,
  p_codigo text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estado jsonb;
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  wallet public.vip_wallets%rowtype;
  convertido_hoy bigint;
  limite_diario bigint := 50;
  tasa integer := 100;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  insert into public.vip_wallets (usuario_id)
  values (usuario_limpio)
  on conflict (usuario_id) do nothing;

  select *
  into wallet
  from public.vip_wallets
  where usuario_id = usuario_limpio;

  select coalesce(sum(vip_coins_spent), 0)
  into convertido_hoy
  from public.vip_coin_conversions
  where usuario_id = usuario_limpio
    and created_at >= date_trunc('day', now());

  return jsonb_build_object(
    'ok', true,
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    ),
    'conversion', jsonb_build_object(
      'rate', tasa,
      'dailyLimitVipCoins', limite_diario,
      'convertedTodayVipCoins', convertido_hoy,
      'remainingTodayVipCoins', greatest(0, limite_diario - convertido_hoy)
    )
  );
end;
$$;

create or replace function public.convertir_monedas_vip(
  p_usuario text,
  p_codigo text default null,
  p_vip_coins bigint default 0
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  estado jsonb;
  usuario_limpio text := btrim(coalesce(p_usuario, ''));
  cantidad bigint := greatest(0, coalesce(p_vip_coins, 0));
  tasa integer := 100;
  limite_diario bigint := 50;
  convertido_hoy bigint;
  disponible_hoy bigint;
  monedas_normales bigint;
  wallet public.vip_wallets%rowtype;
  saldo_normal bigint;
  conversion_id bigint;
begin
  estado := public.obtener_estado_vip(usuario_limpio, p_codigo);

  if coalesce((estado->>'is_vip')::boolean, false) is not true then
    return jsonb_build_object(
      'ok', false,
      'mensaje', coalesce(estado->>'mensaje', 'No se pudo validar tu acceso VIP.')
    );
  end if;

  if cantidad <= 0 then
    return jsonb_build_object('ok', false, 'mensaje', 'Ingresa una cantidad valida de monedas VIP.');
  end if;

  if cantidad > limite_diario then
    return jsonb_build_object('ok', false, 'mensaje', 'La conversion supera el limite diario VIP.');
  end if;

  insert into public.vip_wallets (usuario_id)
  values (usuario_limpio)
  on conflict (usuario_id) do nothing;

  select *
  into wallet
  from public.vip_wallets
  where usuario_id = usuario_limpio
  for update;

  if wallet.vip_coins < cantidad then
    return jsonb_build_object('ok', false, 'mensaje', 'No tienes suficientes monedas VIP.');
  end if;

  select coalesce(sum(vip_coins_spent), 0)
  into convertido_hoy
  from public.vip_coin_conversions
  where usuario_id = usuario_limpio
    and created_at >= date_trunc('day', now());

  disponible_hoy := greatest(0, limite_diario - convertido_hoy);

  if cantidad > disponible_hoy then
    return jsonb_build_object(
      'ok', false,
      'mensaje', 'Ya alcanzaste el limite diario de conversion VIP.',
      'remainingTodayVipCoins', disponible_hoy
    );
  end if;

  monedas_normales := cantidad * tasa;

  update public.vip_wallets
  set vip_coins = vip_coins - cantidad,
      updated_at = now()
  where usuario_id = usuario_limpio
  returning *
  into wallet;

  insert into public.usuario_monedas (usuario_id, saldo)
  values (usuario_limpio, monedas_normales)
  on conflict (usuario_id) do update
    set saldo = public.usuario_monedas.saldo + excluded.saldo,
        updated_at = now()
  returning saldo
  into saldo_normal;

  insert into public.vip_coin_conversions (
    usuario_id,
    vip_coins_spent,
    normal_coins_received,
    conversion_rate
  )
  values (
    usuario_limpio,
    cantidad,
    monedas_normales,
    tasa
  )
  returning id
  into conversion_id;

  insert into public.vip_wallet_transactions (
    usuario_id,
    tipo,
    vip_coins_delta,
    normal_coins_delta,
    source,
    reference_id,
    detail
  )
  values (
    usuario_limpio,
    'convert',
    -cantidad,
    monedas_normales,
    'vip_conversion',
    conversion_id::text,
    jsonb_build_object('rate', tasa, 'dailyLimitVipCoins', limite_diario)
  );

  return jsonb_build_object(
    'ok', true,
    'mensaje', 'Conversion VIP completada.',
    'wallet', jsonb_build_object(
      'usuario_id', wallet.usuario_id,
      'vipCoins', wallet.vip_coins,
      'vipXp', wallet.vip_xp,
      'vipTickets', wallet.vip_tickets,
      'updated_at', wallet.updated_at
    ),
    'conversion', jsonb_build_object(
      'id', conversion_id,
      'vipCoinsSpent', cantidad,
      'normalCoinsReceived', monedas_normales,
      'rate', tasa,
      'dailyLimitVipCoins', limite_diario,
      'convertedTodayVipCoins', convertido_hoy + cantidad,
      'remainingTodayVipCoins', greatest(0, limite_diario - convertido_hoy - cantidad)
    ),
    'normalCoinsBalance', saldo_normal
  );
end;
$$;

create or replace function public.vip_bingo_generar_carton()
returns jsonb
language plpgsql
as $$
declare
  b integer[];
  i integer[];
  n integer[];
  g integer[];
  o integer[];
  card integer[] := '{}';
  fila integer;
begin
  select array_agg(valor) into b from (select valor from generate_series(1, 15) valor order by random() limit 5) s;
  select array_agg(valor) into i from (select valor from generate_series(16, 30) valor order by random() limit 5) s;
  select array_agg(valor) into n from (select valor from generate_series(31, 45) valor order by random() limit 5) s;
  select array_agg(valor) into g from (select valor from generate_series(46, 60) valor order by random() limit 5) s;
  select array_agg(valor) into o from (select valor from generate_series(61, 75) valor order by random() limit 5) s;

  for fila in 1..5 loop
    card := card || b[fila] || i[fila] || case when fila = 3 then 0 else n[fila] end || g[fila] || o[fila];
  end loop;

  return to_jsonb(card);
end;
$$;

create or replace function public.vip_bingo_numero_marcado(p_card jsonb, p_marked jsonb, p_index integer)
returns boolean
language plpgsql
stable
as $$
declare
  valor integer;
begin
  valor := coalesce((p_card->>p_index)::integer, -1);
  if valor = 0 then
    return true;
  end if;

  return exists (
    select 1
    from jsonb_array_elements_text(coalesce(p_marked, '[]'::jsonb)) item(value)
    where item.value = valor::text
  );
end;
$$;

create or replace function public.vip_bingo_tiene_linea(p_card jsonb, p_marked jsonb)
returns boolean
language plpgsql
stable
as $$
declare
  fila integer;
  columna integer;
begin
  if jsonb_array_length(coalesce(p_card, '[]'::jsonb)) <> 25 then
    return false;
  end if;

  for fila in 0..4 loop
    if public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 1)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 2)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 3)
      and public.vip_bingo_numero_marcado(p_card, p_marked, fila * 5 + 4) then
      return true;
    end if;
  end loop;

  for columna in 0..4 loop
    if public.vip_bingo_numero_marcado(p_card, p_marked, columna)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 5)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 10)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 15)
      and public.vip_bingo_numero_marcado(p_card, p_marked, columna + 20) then
      return true;
    end if;
  end loop;

  if public.vip_bingo_numero_marcado(p_card, p_marked, 0)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 6)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 12)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 18)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 24) then
    return true;
  end if;

  if public.vip_bingo_numero_marcado(p_card, p_marked, 4)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 8)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 12)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 16)
    and public.vip_bingo_numero_marcado(p_card, p_marked, 20) then
    return true;
  end if;

  return false;
end;
$$;

create or replace function public.vip_bingo_payload(p_room_id text, p_usuario text)
returns jsonb
language plpgsql
stable
as $$
declare
  sala record;
  jugador record;
  jugador_encontrado boolean := false;
  jugadores jsonb;
begin
  select *
  into sala
  from public.vip_bingo_rooms
  where id = p_room_id;

  if not found then
    return jsonb_build_object('ok', false, 'mensaje', 'Sala VIP no encontrada.');
  end if;

  select *
  into jugador
  from public.vip_bingo_players
  where room_id = p_room_id
    and usuario_id = p_usuario;
  jugador_encontrado := found;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'usuario_id', usuario_id,
      'joined_at', joined_at
    )
    order by joined_at
  ), '[]'::jsonb)
  into jugadores
  from public.vip_bingo_players
  where room_id = p_room_id;

  return jsonb_build_object(
    'ok', true,
    'room', jsonb_build_object(
      'id', sala.id,
      'created_by', sala.created_by,
      'status', sala.status,
      'called_numbers', sala.called_numbers,
      'winner_usuario_id', sala.winner_usuario_id,
      'created_at', sala.created_at,
      'updated_at', sala.updated_at
    ),
    'player', case when not jugador_encontrado then null else jsonb_build_object(
      'usuario_id', jugador.usuario_id,
      'card', jugador.card,
      'marked_numbers', jugador.marked_numbers,
      'joined_at', jugador.joined_at,
      'updated_at', jugador.updated_at
    ) end,
    'players', jugadores
  );
end;
$$;

