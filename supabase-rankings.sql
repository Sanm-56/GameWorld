create or replace function public.reiniciar_temporada_competitiva(p_nombre text default null)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  nueva_id text := 'temporada-' || to_char(now() at time zone 'utc', 'YYYY-MM-DD-HH24MISS');
  nuevo_nombre text := coalesce(nullif(btrim(p_nombre), ''), 'Temporada ' || to_char(now() at time zone 'utc', 'YYYY-MM'));
  temporada_anterior record;
begin
  select *
  into temporada_anterior
  from public.temporadas
  where activa = true
  order by fecha_inicio desc
  limit 1;

  update public.temporadas
  set activa = false,
      fecha_fin = coalesce(fecha_fin, now())
  where activa = true;

  update public.temporadas_nivel
  set activa = false,
      fecha_fin = coalesce(fecha_fin, now())
  where activa = true;

  insert into public.temporadas (id, nombre, fecha_inicio, activa)
  values (nueva_id, nuevo_nombre, now(), true);

  insert into public.temporadas_nivel (id, nombre, fecha_inicio, activa)
  values (nueva_id, nuevo_nombre, now(), true)
  on conflict (id) do update set
    nombre = excluded.nombre,
    fecha_inicio = excluded.fecha_inicio,
    activa = true,
    fecha_fin = null;

  if temporada_anterior.id is not null then
    insert into public.historial_temporadas_nivel (
      usuario_id,
      temporada_id,
      nivel_anterior,
      nivel_nuevo,
      xp_anterior,
      xp_nuevo
    )
    select
      usuario_id,
      temporada_anterior.id,
      nivel,
      greatest(nivel - 3, 1),
      xp,
      public.xp_acumulado_para_nivel(greatest(nivel - 3, 1))
    from public.progreso_nivel
    on conflict (usuario_id, temporada_id) do nothing;
  end if;

  update public.progreso_nivel
  set nivel = greatest(nivel - 3, 1),
      xp = public.xp_acumulado_para_nivel(greatest(nivel - 3, 1)),
      temporada_id = nueva_id,
      updated_at = now();

  return nueva_id;
end;
$$;
create or replace function public.limpiar_datos_usuario_torneo(usuario_borrado text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  objetivo record;
begin
  if usuario_borrado is null or btrim(usuario_borrado) = '' then
    return;
  end if;

  for objetivo in
    select *
    from (values
      ('ranking', 'usuario'),
      ('ranking', 'usuario_id'),
      ('ranking_ajedrez', 'usuario'),
      ('ranking_ajedrez', 'usuario_id'),
      ('ranking_domino', 'usuario'),
      ('ranking_domino', 'usuario_id'),
      ('ranking_damas', 'usuario'),
      ('ranking_damas', 'usuario_id'),
      ('partidas', 'usuario'),
      ('partidas', 'usuario_id'),
      ('estadisticas_logros', 'usuario'),
      ('progreso_nivel', 'usuario_id'),
      ('historial_xp', 'usuario_id'),
      ('recompensas_desbloqueadas', 'usuario_id')
    ) as pendientes(tabla, columna)
    where to_regclass('public.' || pendientes.tabla) is not null
      and exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = pendientes.tabla
          and column_name = pendientes.columna
      )
  loop
    execute format('delete from public.%I where %I = $1', objetivo.tabla, objetivo.columna)
    using usuario_borrado;
  end loop;
end;
$$;

