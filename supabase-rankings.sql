create or replace function public.xp_requerido_nivel(nivel_actual integer)
returns integer
language sql
immutable
as $$
  select case
    when nivel_actual >= 3000 then 0
    else round(
      220
      + (greatest(nivel_actual - 1, 0) * 18)
      + (power(greatest(nivel_actual - 1, 0), 1.18) * 14)
    )::integer * case when nivel_actual >= 2340 then 4 else 1 end
  end;
$$;

create or replace function public.calcular_nivel_por_xp(xp_total bigint)
returns integer
language plpgsql
immutable
as $$
declare
  nivel_actual integer := 1;
  acumulado bigint := 0;
  requisito integer;
begin
  while nivel_actual < 3000 loop
    requisito := public.xp_requerido_nivel(nivel_actual);
    exit when greatest(xp_total, 0) < acumulado + requisito;
    acumulado := acumulado + requisito;
    nivel_actual := nivel_actual + 1;
  end loop;

  return nivel_actual;
end;
$$;

drop function if exists public.xp_acumulado_para_nivel(integer) cascade;

create or replace function public.xp_acumulado_para_nivel(nivel_objetivo integer)
returns bigint
language plpgsql
immutable
as $$
declare
  nivel_limpio integer := least(greatest(coalesce(nivel_objetivo, 1), 1), 3000);
  nivel_actual integer := 1;
  acumulado bigint := 0;
begin
  while nivel_actual < nivel_limpio loop
    acumulado := acumulado + public.xp_requerido_nivel(nivel_actual);
    nivel_actual := nivel_actual + 1;
  end loop;

  return acumulado;
end;
$$;

